/* global __dirname, Buffer */
const fs = require('node:fs/promises');
const path = require('node:path');
const zlib = require('node:zlib');
const { promisify } = require('node:util');

const BULK_DATA_URL = 'https://api.scryfall.com/bulk-data';
const OUT = path.join(__dirname, '..', 'services', 'generated', 'magic-card-name-catalog.ts');
const gunzip = promisify(zlib.gunzip);

function normalize(value) {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u2010-\u2015]/g, '-')
    .replace(/[|]/g, 'l')
    .replace(/&/g, ' and ')
    .replace(/\b0f\b/gi, 'of')
    .replace(/[^a-z0-9/ ]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function aliasesFor(card) {
  const names = new Set([card.name].filter(Boolean));
  if (Array.isArray(card.card_faces)) {
    for (const face of card.card_faces) {
      if (face && face.name) names.add(face.name);
    }
  }
  for (const name of [...names]) {
    for (const part of name.split(/\s*\/\/\s*/)) {
      if (part.trim()) names.add(part.trim());
    }
  }
  return [...new Set([...names].map(normalize).filter(Boolean))].filter((alias) => alias !== normalize(card.name));
}

async function main() {
  const bulkResponse = await fetch(BULK_DATA_URL, { headers: { 'User-Agent': 'TradingDocksCatalogGenerator/1.0' } });
  if (!bulkResponse.ok) throw new Error(`Scryfall bulk metadata failed: ${bulkResponse.status}`);
  const bulk = await bulkResponse.json();
  const oracleBulk = Array.isArray(bulk.data)
    ? bulk.data.find((entry) => entry.type === 'oracle_cards')
    : bulk.type === 'oracle_cards'
      ? bulk
      : null;
  const downloadUri = oracleBulk?.jsonl_download_uri ?? oracleBulk?.download_uri;
  if (!downloadUri) throw new Error('Scryfall bulk metadata did not include oracle_cards download URI.');
  const cardsResponse = await fetch(downloadUri, { headers: { 'User-Agent': 'TradingDocksCatalogGenerator/1.0' } });
  if (!cardsResponse.ok) throw new Error(`Scryfall oracle cards download failed: ${cardsResponse.status}`);
  const bytes = Buffer.from(await cardsResponse.arrayBuffer());
  const text = downloadUri.endsWith('.gz') ? (await gunzip(bytes)).toString('utf8') : bytes.toString('utf8');
  const cards = downloadUri.includes('.jsonl')
    ? text.split(/\r?\n/).filter(Boolean).map((line) => JSON.parse(line))
    : JSON.parse(text);
  const byOracle = new Map();
  for (const card of cards) {
    if (!card || !card.name || !card.oracle_id || !card.id) continue;
    if (card.digital) continue;
    const normalizedName = normalize(card.name);
    if (!normalizedName) continue;
    const existing = byOracle.get(card.oracle_id);
    const entry = existing ?? {
      n: card.name,
      o: card.oracle_id,
      s: card.id,
      a: [],
    };
    if (!existing || String(card.released_at ?? '') > String(existing.releasedAt ?? '')) {
      entry.n = card.name;
      entry.s = card.id;
      entry.releasedAt = card.released_at ?? '';
    }
    for (const alias of aliasesFor(card)) {
      if (!entry.a.includes(alias)) entry.a.push(alias);
    }
    byOracle.set(card.oracle_id, entry);
  }
  const catalog = [...byOracle.values()]
    .map(({ releasedAt, ...entry }) => ({ ...entry, a: entry.a.length ? entry.a.sort() : undefined }))
    .sort((left, right) => left.n.localeCompare(right.n));
  const sourceUpdatedAt = oracleBulk.updated_at ?? new Date().toISOString();
  const generatedAt = new Date().toISOString();
  const content = `// Generated by mobile/scripts/generate-magic-name-catalog.cjs. Do not edit by hand.\n` +
    `export type GeneratedMagicNameCatalogEntry = { n: string; o: string; s: string; a?: string[] };\n` +
    `export const MAGIC_NAME_CATALOG_SOURCE = ${JSON.stringify({ provider: 'scryfall', bulkDataType: 'oracle-cards', sourceUpdatedAt, generatedAt }, null, 2)} as const;\n` +
    `export const MAGIC_NAME_CATALOG: readonly GeneratedMagicNameCatalogEntry[] = ${JSON.stringify(catalog)};\n`;
  await fs.writeFile(OUT, content, 'utf8');
  console.log(`Generated ${catalog.length} Magic oracle names at ${OUT}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});


