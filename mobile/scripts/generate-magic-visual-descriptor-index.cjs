#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const { Buffer } = require('node:buffer');

const args = new Map();
for (let index = 2; index < process.argv.length; index += 2) {
  args.set(process.argv[index], process.argv[index + 1]);
}

const sourcePath = args.get('--source');
const outPath = args.get('--out') ?? 'services/generated/magic-visual-descriptor-index.ts';
if (!sourcePath) {
  console.error('Usage: npm run catalog:magic-visual-descriptors -- --source ./tmp/scryfall-visual-descriptors.json --out services/generated/magic-visual-descriptor-index.ts');
  process.exit(1);
}

const source = JSON.parse(fs.readFileSync(path.resolve(process.cwd(), sourcePath), 'utf8'));
if (!Array.isArray(source.records)) {
  console.error('Descriptor source must be JSON with a records array.');
  process.exit(1);
}

const records = source.records.map((record) => {
  for (const key of ['oracleId', 'scryfallId', 'name', 'hash']) {
    if (typeof record[key] !== 'string' || !record[key]) {
      throw new Error(`Descriptor record is missing ${key}.`);
    }
  }
  return {
    o: record.oracleId,
    s: record.scryfallId,
    n: record.name,
    c: typeof record.setCode === 'string' ? record.setCode : null,
    cn: typeof record.collectorNumber === 'string' ? record.collectorNumber : null,
    h: record.hash.toLowerCase().replace(/[^a-f0-9]/g, '').padStart(16, '0').slice(-16),
  };
});

const generatedAt = new Date().toISOString();
const output = `// Generated by mobile/scripts/generate-magic-visual-descriptor-index.cjs. Do not edit by hand.
export type GeneratedMagicVisualDescriptorRecord = {
  o: string;
  s: string;
  n: string;
  c: string | null;
  cn: string | null;
  h: string;
};

export const MAGIC_VISUAL_DESCRIPTOR_INDEX_SOURCE = ${JSON.stringify({
  provider: 'scryfall',
  source: source.source ?? sourcePath,
  generatedAt,
  algorithm: 'luma_phash_8x8_v1',
  refreshCommand: 'npm run catalog:magic-visual-descriptors -- --source ./tmp/scryfall-visual-descriptors.json --out services/generated/magic-visual-descriptor-index.ts',
  notes: 'Compact descriptors only. Do not commit source artwork images.',
}, null, 2)} as const;

export const MAGIC_VISUAL_DESCRIPTOR_RECORDS: readonly GeneratedMagicVisualDescriptorRecord[] = ${JSON.stringify(records)} as const;

export const MAGIC_VISUAL_DESCRIPTOR_INDEX_STATS = {
  recordCount: MAGIC_VISUAL_DESCRIPTOR_RECORDS.length,
  storageBytes: ${Buffer.byteLength(JSON.stringify(records), 'utf8')},
} as const;
`;

fs.writeFileSync(path.resolve(process.cwd(), outPath), output);
console.log(`Wrote ${records.length} visual descriptors to ${outPath}.`);
