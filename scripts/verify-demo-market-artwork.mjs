// Run explicitly when refreshing the landing demo. No provider API calls at page load.
// Every persisted URL comes from an exact card response (or the provider's own static data).
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { setTimeout } from "node:timers/promises";
import sharp from "sharp";
import { isApprovedArtworkUrl, scryfallCard, pokemonCard, japanesePokemonCard, lorcastCard, onePieceCard } from "../src/lib/card-artwork/providers/index.ts";

const headers = { "User-Agent": "TradingDocks/1.0 (homepage artwork verification)", Accept: "application/json" };
async function json(url) {
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}
const cards = [];
for (const id of ["66024e69-ad60-4c9a-a0ca-da138d33ad80", "b61634ae-05be-4b56-8ebb-9d4ade902e42", "d5806e68-1054-458e-866d-1f2470f682b2", "9f37c5b6-a59c-45cd-9a99-e9357fe9ea1b", "3aad15a2-8a1b-4460-9b06-e85863081878"]) {
  cards.push(scryfallCard(await json(`https://api.scryfall.com/cards/${id}`)));
  await setTimeout(110);
}
// The same project's maintained source data avoids dependence on API availability.
const sets = await json("https://raw.githubusercontent.com/PokemonTCG/pokemon-tcg-data/master/sets/en.json");
for (const [setId, ids] of [["sv8", ["sv8-238"]], ["sv3pt5", ["sv3pt5-199", "sv3pt5-205"]]]) {
  const data = await json(`https://raw.githubusercontent.com/PokemonTCG/pokemon-tcg-data/master/cards/en/${setId}.json`);
  for (const id of ids) {
    const card = data.find((entry) => entry.id === id);
    if (!card) throw new Error(`Missing Pokémon printing ${id}`);
    cards.push(pokemonCard(card, sets.find((set) => set.id === setId)));
  }
}
for (const id of ["SV2a-025", "SV2a-006", "SV2a-151"]) cards.push(japanesePokemonCard(await json(`https://api.tcgdex.net/v2/ja/cards/${id}`)));
for (const number of ["42", "23", "115"]) {
  cards.push(lorcastCard(await json(`https://api.lorcast.com/v0/cards/1/${number}`)));
  await setTimeout(110);
}
for (const id of ["OP01-003", "OP01-025", "OP01-016"]) {
  const data = await json(`https://optcgapi.com/api/sets/card/${id}/`);
  const card = data.find((entry) => entry.card_image_id === id);
  if (!card) throw new Error(`Missing exact One Piece printing ${id}`);
  cards.push(onePieceCard(card));
}
const verified = [];
for (const card of cards) {
  const images = [];
  for (const url of new Set([card.imageUrl, card.thumbnailUrl])) {
    if (!isApprovedArtworkUrl(card.provider, card.game, url)) throw new Error(`Unapproved image for ${card.name}: ${url}`);
    const response = await fetch(url, { headers: { "User-Agent": headers["User-Agent"] }, signal: AbortSignal.timeout(25000), redirect: "error" });
    if (!response.ok || !response.headers.get("content-type")?.startsWith("image/")) throw new Error(`Image failed: ${url} (${response.status})`);
    const bytes = Buffer.from(await response.arrayBuffer());
    const metadata = await sharp(bytes).metadata();
    if (!metadata.width || !metadata.height || metadata.width < 100 || metadata.height < metadata.width) throw new Error(`Invalid card image: ${url}`);
    images.push({ url, width: metadata.width, height: metadata.height, contentType: response.headers.get("content-type"), sha256: createHash("sha256").update(bytes).digest("hex") });
  }
  verified.push({ ...card, verification: { verifiedAt: new Date().toISOString(), images } });
  console.log(`Verified ${card.game}: ${card.name} (${card.providerId})`);
}
// Publish the manifest only after every card and both sizes pass verification.
await mkdir("src/lib/card-artwork", { recursive: true });
await writeFile("src/lib/card-artwork/verified-demo-artwork.ts", `// Generated by scripts/verify-demo-market-artwork.mjs. Do not hand-edit image URLs.\nexport const VERIFIED_DEMO_ARTWORK = ${JSON.stringify(verified, null, 2)} as const;\n`);
